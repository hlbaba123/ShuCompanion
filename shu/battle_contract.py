"""Narrow, explicit one-start authority for a single MAA job.

Intent and planning remain model responsibilities. This admission policy only
bounds external effects; prose generated by a model never grants permission.
"""
from __future__ import annotations

import copy
import re

from .leader_policy import _number, research_stage_codes, TaskSpecError

_START = re.compile(r'(?:开始|启动|发起|执行|运行|点击|让)[^，,。；;！？!?\n]{0,24}'
                    r'(?:MAA[^，,。；;！？!?\n]{0,12}(?:开始|启动|开打|战斗|作战)|自动(?:战斗|作战))|开打|开战', re.I)
_DENY = re.compile(r'(?:不(?:要|用|必|得|能|需(?:要)?|再)?|别|禁止|无需|暂不|先不|尚不|未)\s*'
                   r'(?:点击|进行|执行|发起|让)?\s*(?:MAA\s*)?(?:开始|启动|开打|开战|自动(?:战斗|作战))', re.I)
_LATER = re.compile(r'以后|后续|将来|未来|下次|到时候|稍后|之后再|等.{0,16}再')
_QUESTION = re.compile(r'如何|怎么|怎样|为什么|会怎样|能否|是否|假如|假设|例如|比如|举例|[？?]')
_CONDITION = re.compile(r'如果([^，,。；;！？!?\n（）()]{0,80}?)(?=就|则|[，,。；;！？!?\n（）()]|$)')
_TOOL_ACTION = re.compile(r'(?:MAA|黍|工具)[^，,。；;！？!?\n]{0,24}'
                          r'(?:导航|打开游戏|启动游戏|唤醒|截图|识别|到达[^，,。；;\n]{0,8}(?:页面|界面))',re.I)
_GENERIC_CONDITION = re.compile(r'(?:借助)?(?:MAA|黍|它|工具)?(?:可以|不可以|能|不能|能够|无法|可行|支持)'
                                r'(?:实现|做到)?(?:的话)?\Z',re.I)
_HYPOTHETICAL = re.compile(r'有一天|有朝一日|假想|万一|未来|以后|将来')
_BATTLE_CONDITION = re.compile(r'自动(?:战斗|作战)|开战|开打|开始作战|开始战斗',re.I)
_COUNT = re.compile(r'(?:刷|连打|重复|打|作战|战斗|运行|执行|启动)[^，,。；;\n]{0,12}?'
                    r'([0-9]{1,4}|[零〇一二两三四五六七八九十百千]{1,6})\s*(?:次|局|轮|遍)')
_FIND_JOB = re.compile(r'(?<!已)(?:查|找|搜|获取)(?!到的|过的)[^，,。；;\n]{0,48}(?:作业|攻略|copilot)', re.I)
_IMPORT_JOB = re.compile(r'(?<!已)(?:导入|载入|加载)(?!的|过)[^，,。；;\n]{0,30}(?:MAA|作业)|'
                         r'作业[^，,。；;\n]{0,20}(?<!已)(?:导入|载入|加载)(?!的|过)', re.I)
_BATTLE_TAB = re.compile(r'[「“"]?自动(?:战斗|作战)[」”"]?\s*(?:界面|页面|页签|选项卡|栏目)')
_SEQUENCED_RUN = re.compile(
    r'(?:开始|然后|最后|随后|接着|之后|后|并且|并|再|导入(?:\s*MAA)?)\s*(?:让\s*MAA\s*)?'
    r'(?:开始\s*)?(?:执行|运行|启动)(?=\s*(?:$|[，,。；;！？!?\n（(]|'
    r'一次|[1-9]\s*次|这(?:份|个)作业|作业|MAA(?!\s*(?:作业页|界面|页面|选项卡))|'
    r'自动战斗|自动作战))|开始(?:自动)?(?:作战|战斗)', re.I)
_RESTRICTED_COMPOUND = re.compile(
    r'(?:仅|只)(?:需要|要|用)?\s*(?:查(?:找|询)?|导入|加载)(?![^，,。；;\n]{0,32}(?:并|后|再)(?:开始|运行|执行|启动))|'
    r'(?:不(?:要|用|必|得|能|需(?:要)?)?|别|禁止|无需|暂不|先不)\s*(?:导入|执行|运行|打(?:这关|怪))|'
    r'(?:等|待|需要)\s*(?:我|用户)?\s*(?:授权|同意|确认)|基建|'+
    r'(?:清完|清空|打完|通关|刷完)(?:所有|全部|整个|整)?[^，,。；;\n]{0,12}(?:活动|关卡)')
_RESTRICTIONS = {'battle_start': True, 'direct_game_input': 'navigation_only',
                 'medicine_limit': 0, 'premium_limit': 0}


def _tool_conditionals(text):
    """A navigation-tool choice is not a hypothetical battle request.

    Keep the original request intact. Only capability conditions concerning
    the route/tool may precede the independently requested MAA start; asking
    about a battle, future possibilities and conditional starts stay blocked.
    """
    if '如果' not in text:
        return True
    if _HYPOTHETICAL.search(text):
        return False
    conditions = list(_CONDITION.finditer(text))
    if len(conditions) != text.count('如果'):
        return False
    for match in conditions:
        clause = re.sub(r'\s+', '', match.group(1))
        if not clause or _BATTLE_CONDITION.search(clause):
            return False
        context = text[max(0,match.start()-72):match.end()]
        if not (_TOOL_ACTION.search(context)
                or _GENERIC_CONDITION.fullmatch(clause) and _TOOL_ACTION.search(text)):
            return False
    return True


def _requested(contract):
    if (contract.get('current_deliverable') != 'gameplay'
            or (contract.get('task_spec') or {}).get('kind') != 'repeat_stage'):
        return False
    spec = contract.get('task_spec') or {}
    if spec.get('repeat_count') not in (None, 1) or spec.get('unresolved'):
        return False
    text = contract.get('original_user_request', contract.get('user_request'))
    if (not isinstance(text, str) or not text.strip() or _DENY.search(text)
            or _LATER.search(text) or _QUESTION.search(text) or not _START.search(text)
            or _FIND_JOB.search(text) or not _tool_conditionals(text)):
        return False
    # Literal multiple-run objectives cannot be narrowed when intent parsing
    # omitted their count. Preserve them for a later supported runner.
    if any(_number(match.group(1)) != 1 for match in _COUNT.finditer(text)):
        return False
    return True


def import_then_start_requested(text):
    """Read an explicit immediate execution endpoint from the user's own words."""
    if not isinstance(text, str):
        return False
    action_text = _BATTLE_TAB.sub('作业页', text)
    return bool((_FIND_JOB.search(text) or _IMPORT_JOB.search(text))
                and (_START.search(action_text) or _SEQUENCED_RUN.search(action_text))
                and not (_DENY.search(text) or _LATER.search(text) or _QUESTION.search(text)
                         or _RESTRICTED_COMPOUND.search(text))
                and _tool_conditionals(text))


def _compound_request(contract):
    text = contract.get('original_user_request', contract.get('user_request'))
    spec = contract.get('task_spec') or {}
    scope = contract.get('import_scope') or {}
    if (contract.get('intent') not in (None, 'execute', 'modify')
            or contract.get('current_deliverable') not in ('maa_import', 'gameplay', 'copilot_codes')
            or spec.get('kind') not in ('repeat_stage', 'import', 'lookup')
            or spec.get('repeat_count') not in (None, 1)
            or not import_then_start_requested(text)
            or ('普通' in text and '突袭' in text) or scope.get('difficulty') == 3):
        return False
    if any(_number(match.group(1)) != 1 for match in _COUNT.finditer(text)):
        return False
    try:
        literal = research_stage_codes({'user_request': text})
    except TaskSpecError:
        return False
    selection = scope.get('stage_codes') or []
    declared = contract.get('target_stage_codes') or ([spec['stage_code']] if spec.get('stage_code') else [])
    if len(literal) == 1 and any(codes and set(codes) != set(literal) for codes in (selection, declared)):
        return False
    return len(selection) <= 1 and len(literal) <= 1


def authorize(contract):
    """Copy a contract and derive effect limits from its exact current request."""
    result = copy.deepcopy(contract)
    result.update(allow_start=False, attempt_limit=0, workflow_scope='gui_assist',
                  execution_restrictions={'battle_start': False, 'direct_game_input': False})
    if _compound_request(result):
        result.update(current_deliverable='maa_import', allow_start=True, attempt_limit=1,
                      workflow_scope='maa_import_then_battle', execution_restrictions=dict(_RESTRICTIONS))
        result['task_spec'].update(kind='import', repeat_count=1)
        scope = result.get('import_scope') or {}
        text = result.get('original_user_request', result.get('user_request'))
        codes = result.get('target_stage_codes') or [result['task_spec'].get('stage_code')]
        if scope.get('kind') in (None, 'unspecified') and len(codes) == 1 and codes[0]:
            scope = {'kind': 'stages', 'stage_codes': codes, 'ordinal': None,
                     'group_hint': scope.get('group_hint', ''), 'difficulty': None}
        if scope.get('kind') in ('stages', 'ordinal'):
            result['import_scope'] = {**scope, 'difficulty': 2 if '突袭' in text else 1 if '普通' in text
                                      else scope.get('difficulty') or 1}
    elif _requested(result) and not import_then_start_requested(result.get('original_user_request', result.get('user_request'))):
        result.update(allow_start=True, attempt_limit=1, workflow_scope='maa_battle_start',
                      execution_restrictions=dict(_RESTRICTIONS))
    return result


def compound_authorized(contract):
    return (isinstance(contract, dict) and contract.get('current_deliverable') == 'maa_import'
            and contract.get('workflow_scope') == 'maa_import_then_battle'
            and contract.get('allow_start') is True and type(contract.get('attempt_limit')) is int
            and contract['attempt_limit'] == 1 and contract.get('execution_restrictions') == _RESTRICTIONS
            and _compound_request(contract))


def authorized(contract):
    """Validate both the original request and persisted, bounded authority."""
    return compound_authorized(contract) or (isinstance(contract, dict) and _requested(contract)
            and contract.get('allow_start') is True
            and type(contract.get('attempt_limit')) is int and contract['attempt_limit'] == 1
            and contract.get('workflow_scope') == 'maa_battle_start'
            and contract.get('execution_restrictions') == _RESTRICTIONS)
